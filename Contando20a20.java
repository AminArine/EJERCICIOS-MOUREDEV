import java.util.Scanner;

public class Contando20a20 {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        

      //Esta es la forma de controlar las iteraciones
        	for (int i=320;i>=160 ;i-=20) {
        		
        		System.out.print(i +" ");
        		
        	}
       
        

        sc.close();
    }
}